import assert from 'node:assert/strict'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { closeAllDbs, getDb, memoryDbPath, projectLabel } from './lib/index.js'

const ws = mkdtempSync(join(tmpdir(), 'dsh-meow-db-'))
assert.equal(projectLabel('全局'), '本工作区通用')
assert.equal(projectLabel('global'), '本工作区通用')
assert.equal(projectLabel(null), '未标记')
try {
  const memory = getDb(ws)
  const q = memory.insertQuarantine({ level: 'fact', content: '暂存测试', theme: '插件开发', reason: 'judge uncertain' })
  assert.equal(memory.listQuarantine().length, 1)
  assert.equal(memory.listQuarantine()[0].id, q.id)
  const promoted = memory.promoteQuarantine(q.id)
  assert.equal(promoted?.content, '暂存测试')
  assert.equal(memory.listQuarantine().length, 0)
  assert.equal(memory.list('fact').some((row) => row.id === promoted.id), true)
  memory.deleteMemory('fact', promoted.id)
  const proposal = memory.createThemeProposal({ theme: '插件开发', reason: 'test' })
  assert.equal(memory.getPendingThemeProposal()?.id, proposal.id)
  assert.equal(memory.decideThemeProposal(proposal.id, 'confirmed'), true)
  assert.equal(memory.getPendingThemeProposal(), undefined)
  const later = memory.createThemeProposal({ theme: '稍后测试' })
  assert.equal(memory.decideThemeProposal(later.id, 'later'), true)
  assert.equal(memory.getPendingThemeProposal(), undefined)
  assert.equal(memory.reopenThemeProposal(later.id), true)
  assert.equal(memory.getPendingThemeProposal()?.id, later.id)
  assert.equal(memory.decideThemeProposal(later.id, 'rejected'), true)
  memory.setWorkspaceSetting('theme', '插件开发')
  assert.equal(memory.getWorkspaceSetting('theme'), '插件开发')
  const row = memory.insert({ level: 'fact', content: '主库分类测试', project: null })
  assert.equal(row.domain, 'content')
  const tooling = memory.insert({ level: 'lesson', domain: 'tooling', content: '工具记忆测试', project: 'test' })
  assert.equal(tooling.domain, 'tooling')
  assert.equal(memory.findById(tooling.id)?.row.domain, 'tooling')
  memory.deleteMemory('lesson', tooling.id)
  assert.equal(memory.setThemeMatch('fact', row.id, 1), true)
  assert.equal(memory.deleteMemory('fact', row.id), true)
  assert.equal(memory.findById(row.id), undefined)
  assert.equal(memory.getSoul(), undefined)
  const soul = memory.setSoul('工作区 SOUL')
  assert.equal(soul.content, '工作区 SOUL')
  assert.equal(memory.getSoul()?.content, '工作区 SOUL')
  assert.equal(memory.setSoul('工作区 SOUL 2').content, '工作区 SOUL 2')
  memory.insert({ level: 'fact', content: '维护测试 A', project: null, importance: 1 })
  memory.insert({ level: 'fact', content: '维护测试 B', project: null, importance: 1 })
  const maintenance = memory.maintain({ archiveAfterDays: 9999, maxActive: 1 })
  assert.equal(maintenance.archived, 1)
  assert.equal(memory.list('fact', { status: 'active' }).length, 1)
  closeAllDbs()
  const path = memoryDbPath(ws)
  assert.equal(path, join(ws, '.dsh-scope', 'memory.db'))
  const db = new DatabaseSync(path, { readOnly: true })
  const tables = new Set(db.prepare("select name from sqlite_master where type='table'").all().map((r) => r.name))
  for (const table of ['soul', 'project', 'fact', 'lesson', 'topic', 'rules', 'quarantine', 'theme_proposals', 'workspace_settings']) {
    assert.equal(tables.has(table), true, `missing table ${table}`)
  }
  assert.equal(tables.has('user'), false, 'user table must be absent')
  const factCols = new Set(db.prepare('pragma table_info(fact)').all().map((r) => r.name))
  assert.equal(factCols.has('theme_match'), true)
  db.close()
  console.log('PASS db schema: .dsh-scope DB with quarantine/theme tables and theme_match')
} finally {
  closeAllDbs()
  rmSync(ws, { recursive: true, force: true })
}
